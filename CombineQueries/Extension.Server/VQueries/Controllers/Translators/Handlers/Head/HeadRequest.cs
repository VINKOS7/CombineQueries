using MediatR;
using Newtonsoft.Json;

namespace CombineQueries.Api.Controllers.Translators.Handlers.Head;

// Голова потока: клиент спрашивает, знает ли сервер адрес, который он собрался диктовать.
//
// Само обращение к /head и есть «я не знаю»: знал бы номер - прыгнул бы через /h/. Поэтому
// никакого признака «известен/неизвестен» в запросе нет, он лишний.
public record HeadRequest : IRequest<HeadResponse>
{
    // Адрес фрагмента, который клиент нашёл в своём url. Не хэш: по адресу сервер знает ТЕКСТ,
    // а значит может искать по содержимому - и неважно, чем этот кусок знает клиент.
    //
    // Клиент шлёт САМЫЙ ДЛИННЫЙ из найденных: короткие куски вроде "?limit" встречаются в сотнях
    // адресов и не различают ничего, длинные дают единицы кандидатов.
    [JsonProperty("fragment")] public int Fragment { get; set; }

    // Обрезок номера ИЗВЕСТНОЙ клиенту цепочки - той, что похожа на искомый адрес. Полный номер
    // не влезает: он множит пул. Обрезка хватает, потому что вторую половину работы делает кусок.
    //
    // Сервер складывает одно с другим: берёт адрес этой цепочки, подставляет присланный кусок
    // вместо последнего сегмента - и получает ТОЧНЫЙ адрес, а не список похожих.
    [JsonProperty("base")] public int Base { get; set; } = -1;

    // Очередная подпись общего с хвостом кольца. Полная: /head форвардит сам, значит по правам
    // равен хвосту.
    [JsonProperty("sign")] public int Sign { get; set; }
}
