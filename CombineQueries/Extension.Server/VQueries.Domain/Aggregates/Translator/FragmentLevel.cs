namespace CombineQueries.Domain.Aggregates.Translator;

// Уровень адресации строки словаря = СКОЛЬКО РАЗВЯЗОК нужно, чтобы её назвать.
// Ноль стоит особняком: финитного адреса нет вовсе.
//
// L1 здесь нет намеренно: корни рун-алфавита едут прямо в руне, своего адреса не занимают
// и в таблицу не попадают.
public enum FragmentLevel
{
    // Финитные адреса кончились: адресуется якорем + Развязкой-3, цепь идёт по Jump.
    Infinite = 0,

    // Одна развязка: id < dfaSize.
    L2 = 1,

    // Две развязки: dfaSize <= id < dfaSize*pageCount, id = page*dfaSize + offset.
    L3 = 2
}
