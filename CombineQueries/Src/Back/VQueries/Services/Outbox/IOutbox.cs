using Newtonsoft.Json;

namespace CombineQueries.Api.Services.Outbox;

// Один доставленный адрес: что просили и что пришло снаружи.
public record Delivery(
    [property: JsonProperty("url")] string Url,
    [property: JsonProperty("response")] string Response,
    [property: JsonProperty("elapsedMs")] long ElapsedMs);

// Почтовый ящик отложенных ответов.
//
// Форвард наружу занимает секунды, а бывает и упирается в таймаут - держать на нём клиента значит
// морозить игрока. Поэтому запрос уходит В ФОН, а отвечаем тем, что уже готово. Недоспевшее
// приезжает довеском к ЛЮБОМУ следующему ответу ТОГО ЖЕ клиента.
//
// Ящик разделён по потокам: клиентов на сервере много, и общая очередь отдавала тела тому, кто
// первым спросил. Чужой клиент их выбрасывал - коробки под этот адрес у него нет, - а настоящий
// хозяин ждал вечно.
public interface IOutbox
{
    // Отправляет за адресом в фоне. Тело ляжет в ящик того потока, который за ним послал.
    void Fetch(string url, int stream);

    // Забирает всё, что доспело к этому моменту для этого потока. Забранное из ящика уходит.
    IReadOnlyList<Delivery> Take(int stream);

    // Сколько адресов этого потока ещё в полёте.
    int Pending(int stream);
}
